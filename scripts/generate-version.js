/**
 * Writes src/scaffold/version.ts from package.json so browser-safe code can
 * know the hive-stream version without reading the filesystem.
 *
 * Run as part of `npm run build`; tests/browser-safe-entries.spec.ts fails if
 * the committed file drifts from package.json.
 */
const fs = require('fs');
const path = require('path');

const pkg = require('../package.json');
const target = path.resolve(__dirname, '..', 'src', 'scaffold', 'version.ts');
const source = `// Generated by scripts/generate-version.js — do not edit.\nexport const HIVE_STREAM_VERSION = '${pkg.version}';\n`;

if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== source) {
    fs.writeFileSync(target, source);
    console.log(`Wrote src/scaffold/version.ts (${pkg.version})`);
}
