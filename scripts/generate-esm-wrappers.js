/**
 * Generates ESM wrapper modules over the compiled CJS output.
 *
 * The package intentionally has a single CJS implementation with thin .mjs
 * wrappers re-exporting named bindings, rather than a parallel ESM build.
 * That keeps one copy of every class at runtime (no dual-package hazard:
 * `instanceof Streamer`/`TimeAction` always works regardless of how the
 * consumer imports), while giving ESM consumers real named imports.
 *
 * Run after tsc as part of `npm run build`.
 */
const fs = require('fs');
const path = require('path');

const ENTRIES = [
    { cjs: 'dist/index.js', mjs: 'dist/index.mjs' },
    { cjs: 'dist/testing/index.js', mjs: 'dist/testing/index.mjs' },
    { cjs: 'dist/client/index.js', mjs: 'dist/client/index.mjs' },
    { cjs: 'dist/scaffold/index.js', mjs: 'dist/scaffold/index.mjs' },
    { cjs: 'dist/catalog/index.js', mjs: 'dist/catalog/index.mjs' }
];

const IDENTIFIER = /^[A-Za-z_$][A-Za-z0-9_$]*$/;

for (const entry of ENTRIES) {
    const cjsPath = path.resolve(__dirname, '..', entry.cjs);
    const mjsPath = path.resolve(__dirname, '..', entry.mjs);

    // eslint-disable-next-line global-require
    const mod = require(cjsPath);
    const names = Object.keys(mod)
        .filter((name) => name !== 'default' && name !== '__esModule')
        .filter((name) => IDENTIFIER.test(name))
        .sort();

    if (names.length === 0) {
        throw new Error(`No named exports found in ${entry.cjs} — refusing to write an empty wrapper`);
    }

    const relative = './' + path.basename(entry.cjs);
    const banner = '// Generated by scripts/generate-esm-wrappers.js — do not edit.\n';
    const source = `${banner}import cjs from '${relative}';\n\nexport default cjs;\n\nexport const {\n    ${names.join(',\n    ')}\n} = cjs;\n`;

    fs.writeFileSync(mjsPath, source);
    console.log(`Wrote ${entry.mjs} (${names.length} named exports)`);
}
